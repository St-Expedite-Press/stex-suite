import { createHash, randomUUID } from 'node:crypto';
import { access, copyFile, mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { execFile as execFileCallback, spawn as spawnProcess } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const execFile = promisify(execFileCallback);
const moduleDirectory = path.dirname(fileURLToPath(import.meta.url));
const MAX_COMMAND_OUTPUT = 160_000;
const PROJECT_ID = /^[a-z0-9][a-z0-9-]{0,62}$/;
const corepackEntry = path.join(path.dirname(process.execPath), 'node_modules', 'corepack', 'dist', 'corepack.js');
const now = () => new Date().toISOString();
const digest = (value) => createHash('sha256').update(value).digest('hex');

function slug(value) {
  const result = String(value || 'website').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 44);
  return result || 'website';
}

function cleanTitle(value) {
  const title = String(value || '').trim().replace(/\s+/g, ' ').slice(0, 120);
  if (!title) throw new Error('A project title is required.');
  return title;
}

function projectId(value) {
  if (!PROJECT_ID.test(String(value || ''))) throw new Error('Invalid project id.');
  return value;
}

function sourceFor(title) {
  const heading = String(title).replace(/[<>{}]/g, '');
  return `export default function Home() {\n  return (\n    <main>\n      <p>STEX / Seaxneat draft</p>\n      <h1>${heading}</h1>\n      <p>Nothing here is published. This local preview is a working draft.</p>\n    </main>\n  );\n}\n`;
}

function templateFiles(title) {
  return {
    'next.config.ts': 'import type { NextConfig } from "next";\n\nconst nextConfig: NextConfig = { basePath: process.env.NEXT_BASE_PATH || "" };\nexport default nextConfig;\n',
    'tsconfig.json': `${JSON.stringify({ compilerOptions: { target: 'ES2022', lib: ['dom', 'dom.iterable', 'es2022'], allowJs: false, skipLibCheck: true, strict: true, noEmit: true, esModuleInterop: true, module: 'esnext', moduleResolution: 'bundler', resolveJsonModule: true, isolatedModules: true, jsx: 'preserve', incremental: true }, include: ['next-env.d.ts', '**/*.ts', '**/*.tsx', '.next/types/**/*.ts'], exclude: ['node_modules'] }, null, 2)}\n`,
    'next-env.d.ts': '/// <reference types="next" />\n/// <reference types="next/image-types/global" />\n\n// This file is generated by Next.js.\n',
    'app/layout.tsx': 'import type { Metadata } from "next";\nimport "./globals.css";\n\nexport const metadata: Metadata = { title: "Seaxneat draft" };\nexport default function Layout({ children }: Readonly<{ children: React.ReactNode }>) { return <html lang="en"><body>{children}</body></html>; }\n',
    'app/page.tsx': sourceFor(title),
    'app/globals.css': 'html { font-family: system-ui, sans-serif; background: #f4efe5; color: #182329; } body { margin: 0; } main { max-width: 44rem; margin: 12vh auto; padding: 2rem; } h1 { font-size: clamp(2rem, 8vw, 5rem); margin: .5rem 0; } p { line-height: 1.5; }\n'
  };
}

async function atomic(file, value) {
  await mkdir(path.dirname(file), { recursive: true });
  const temporary = `${file}.${process.pid}.${randomUUID()}.tmp`;
  await writeFile(temporary, value, 'utf8');
  await rename(temporary, file);
}

async function present(file) { try { await access(file); return true; } catch { return false; } }

export function defaultRunner(command, args, cwd, { timeoutMs = 120_000, env } = {}) {
  return execFile(command, args, { cwd, timeout: timeoutMs, windowsHide: true, maxBuffer: MAX_COMMAND_OUTPUT, env: { ...process.env, ...env } }).then(({ stdout = '', stderr = '' }) => ({ ok: true, stdout: String(stdout).slice(-MAX_COMMAND_OUTPUT), stderr: String(stderr).slice(-MAX_COMMAND_OUTPUT) })).catch((error) => ({ ok: false, code: error.code ?? null, stdout: String(error.stdout || '').slice(-MAX_COMMAND_OUTPUT), stderr: String(error.stderr || error.message || '').slice(-MAX_COMMAND_OUTPUT) }));
}

export class SeaxneatStore {
  constructor({ root, runner = defaultRunner, clock = now, previewStarter = null } = {}) {
    if (!root) throw new Error('A Seaxneat state directory is required.');
    this.root = path.resolve(root); this.runner = runner; this.clock = clock; this.previewStarter = previewStarter; this.state = { schemaVersion: 1, projects: [] };
  }

  stateFile() { return path.join(this.root, 'state.json'); }
  projectsDirectory() { return path.join(this.root, 'projects'); }
  projectDirectory(id) { return path.join(this.projectsDirectory(), projectId(id)); }
  workspace(id) { return path.join(this.projectDirectory(id), 'workspace'); }
  pagePath(id) { return path.join(this.workspace(id), 'app', 'page.tsx'); }
  reference(project) { return `stex://seaxneat/project/${project.id}`; }

  async initialize() {
    await mkdir(this.projectsDirectory(), { recursive: true });
    if (await present(this.stateFile())) this.state = JSON.parse(await readFile(this.stateFile(), 'utf8'));
    if (!Array.isArray(this.state.projects)) this.state.projects = [];
    let changed = false;
    for (const project of this.state.projects) {
      if (project.operation?.state === 'running') { project.operation = { ...project.operation, state: 'needs_attention', detail: 'The previous operation was interrupted; inspect the diff or restore the last validated version.', updatedAt: this.clock() }; changed = true; }
    }
    if (changed) await this.save();
    return this;
  }

  async save() { await atomic(this.stateFile(), `${JSON.stringify(this.state, null, 2)}\n`); }
  list() { return this.state.projects.map((project) => this.summary(project)); }
  summary(project) { const { pendingProposal, revisions, messages, ...publicProject } = project; return { ...publicProject, ref: this.reference(project), revisions: revisions.map(({ id, kind, createdAt, sourceHash }) => ({ id, kind, createdAt, sourceHash })), revisionCount: revisions.length, messageCount: messages.length, hasPendingProposal: Boolean(pendingProposal) }; }
  get(id) { const validId = projectId(id); const project = this.state.projects.find((entry) => entry.id === validId); if (!project) throw new Error('Project not found.'); return project; }

  async run(command, args, cwd, options) { return this.runner(command, args, cwd, options); }
  async pnpm(args, cwd, options) {
    // Windows Node installations expose Corepack as a .cmd file, which cannot
    // be launched through execFile. Its JavaScript entry is stable beside the
    // Node binary and avoids relying on a user-global pnpm installation.
    return process.platform === 'win32'
      ? this.run(process.execPath, [corepackEntry, 'pnpm', ...args], cwd, options)
      : this.run('corepack', ['pnpm', ...args], cwd, options);
  }
  async git(args, cwd) { const result = await this.run('git', args, cwd, { timeoutMs: 30_000 }); if (!result.ok) throw Object.assign(new Error(result.stderr || `git ${args[0]} failed.`), { result }); return result; }
  async commitRevision(project, message, kind) {
    const workspace = this.workspace(project.id);
    await this.git(['add', 'app/page.tsx'], workspace); await this.git(['commit', '-m', message], workspace);
    const revision = (await this.git(['rev-parse', 'HEAD'], workspace)).stdout.trim();
    project.revisions.push({ id: revision.slice(0, 12), commit: revision, kind, createdAt: this.clock(), sourceHash: digest(await readFile(this.pagePath(project.id), 'utf8')) });
    project.lastValidatedRevision = revision;
    return revision;
  }

  async create(input) {
    const title = cleanTitle(input?.title); const id = `${slug(title)}-${createHash('sha256').update(`${title}:${this.clock()}:${Math.random()}`).digest('hex').slice(0, 6)}`;
    const workspace = this.workspace(id); await mkdir(workspace, { recursive: true });
    for (const [relative, content] of Object.entries(templateFiles(title))) await atomic(path.join(workspace, relative), content);
    for (const name of ['package.json', 'pnpm-lock.yaml']) await copyFile(path.join(moduleDirectory, '..', 'template', name), path.join(workspace, name));
    await this.git(['init'], workspace); await this.git(['config', 'user.email', 'seaxneat@local.invalid'], workspace); await this.git(['config', 'user.name', 'Seaxneat local alpha'], workspace); await this.git(['add', '.'], workspace); await this.git(['commit', '-m', 'Seed isolated Next.js workspace'], workspace);
    const commit = (await this.git(['rev-parse', 'HEAD'], workspace)).stdout.trim(); const createdAt = this.clock();
    // A Git seed is useful recovery history, but it is not a validated revision
    // until the exact generated workspace has installed and built successfully.
    const project = { id, title, createdAt, updatedAt: createdAt, status: 'provisioning', operation: { state: 'idle', updatedAt: createdAt }, messages: [], revisions: [{ id: commit.slice(0, 12), commit, kind: 'seed', createdAt, sourceHash: digest(await readFile(this.pagePath(id), 'utf8')) }], lastValidatedRevision: null, pendingProposal: null, preview: null };
    this.state.projects.push(project); await this.save();
    const result = await this.build(project);
    if (result.ok) { project.status = 'ready'; project.lastValidatedRevision = commit; }
    else { project.status = 'failed'; project.operation = { state: 'failed', kind: 'provision', detail: (result.stderr || result.stdout || 'Initial build failed.').slice(-4000), updatedAt: this.clock() }; }
    project.updatedAt = this.clock(); await this.save(); return this.summary(project);
  }

  async proposal(id, input) {
    const project = this.get(id); const request = String(input?.message || '').trim().slice(0, 800);
    if (!request) throw new Error('An edit request is required.');
    const source = await readFile(this.pagePath(project.id), 'utf8'); const target = request.replace(/[<>]/g, '').replace(/\s+/g, ' ').slice(0, 140);
    const next = source.replace(/<h1>[^<]*<\/h1>/, `<h1>${target}</h1>`);
    if (next === source) throw new Error('The starter site no longer has the bounded editable heading.');
    const proposal = { id: `proposal-${randomUUID().slice(0, 12)}`, kind: 'bounded-heading-edit', path: 'app/page.tsx', baseHash: digest(source), source: next, request, createdAt: this.clock(), simulator: 'deterministic' };
    project.messages.push({ id: `msg-${randomUUID().slice(0, 12)}`, role: 'user', content: request, createdAt: this.clock() }, { id: `msg-${randomUUID().slice(0, 12)}`, role: 'assistant', content: 'The deterministic simulator prepared a bounded heading edit. Review and apply it explicitly.', createdAt: this.clock(), simulator: 'deterministic' });
    project.pendingProposal = proposal; project.updatedAt = this.clock(); await this.save(); return proposal;
  }

  async build(project) {
    const workspace = this.workspace(project.id); project.operation = { state: 'running', kind: 'build', startedAt: this.clock(), updatedAt: this.clock() }; await this.save();
    const environment = { NEXT_BASE_PATH: `/seaxneat/api/projects/${project.id}/preview` };
    const install = await this.pnpm(['install', '--frozen-lockfile'], workspace, { timeoutMs: 180_000, env: environment });
    const result = install.ok ? await this.pnpm(['build'], workspace, { timeoutMs: 180_000, env: environment }) : install;
    project.operation = result.ok ? { state: 'idle', updatedAt: this.clock() } : { state: 'failed', kind: 'build', detail: (result.stderr || result.stdout || 'Build failed.').slice(-4000), updatedAt: this.clock() }; await this.save(); return result;
  }

  async apply(id, proposalId) {
    const project = this.get(id); const proposal = project.pendingProposal;
    if (!proposal || proposal.id !== proposalId) throw new Error('Pending proposal not found.');
    const current = await readFile(this.pagePath(project.id), 'utf8'); if (digest(current) !== proposal.baseHash) throw new Error('The draft changed after this proposal was created. Request a new edit.');
    project.operation = { state: 'running', kind: 'apply', proposalId, startedAt: this.clock(), updatedAt: this.clock() }; await this.save(); await atomic(this.pagePath(project.id), proposal.source);
    const result = await this.build(project);
    if (!result.ok) { await this.git(['checkout', '--', 'app/page.tsx'], this.workspace(project.id)); project.operation = { state: 'failed', kind: 'apply', detail: 'Build failed; the draft was restored to its last committed source.', updatedAt: this.clock() }; await this.save(); throw Object.assign(new Error(project.operation.detail), { code: 'BUILD_FAILED', output: result }); }
    await this.commitRevision(project, `Apply simulated edit: ${proposal.request.slice(0, 72)}`, 'edit'); project.pendingProposal = null; project.updatedAt = this.clock(); await this.save(); return this.summary(project);
  }

  async dismiss(id, proposalId) { const project = this.get(id); if (!project.pendingProposal || project.pendingProposal.id !== proposalId) throw new Error('Pending proposal not found.'); project.pendingProposal = null; project.updatedAt = this.clock(); await this.save(); return this.summary(project); }
  async diff(id, revision) { const project = this.get(id); const target = project.revisions.find((entry) => entry.id === revision || entry.commit === revision); if (!target) throw new Error('Revision not found.'); return (await this.git(['diff', '--no-ext-diff', `${target.commit}..HEAD`, '--', 'app/page.tsx'], this.workspace(project.id))).stdout; }

  async restore(id, revision) {
    const project = this.get(id); const target = project.revisions.find((entry) => entry.id === revision || entry.commit === revision); if (!target) throw new Error('Revision not found.'); const workspace = this.workspace(project.id);
    project.operation = { state: 'running', kind: 'restore', revision: target.id, startedAt: this.clock(), updatedAt: this.clock() }; await this.save();
    const source = (await this.git(['show', `${target.commit}:app/page.tsx`], workspace)).stdout; await atomic(this.pagePath(project.id), source); const result = await this.build(project);
    if (!result.ok) { project.operation = { state: 'failed', kind: 'restore', detail: 'Restored source did not build; inspect the workspace diff.', updatedAt: this.clock() }; await this.save(); throw Object.assign(new Error(project.operation.detail), { code: 'BUILD_FAILED' }); }
    await this.commitRevision(project, `Restore validated revision ${target.id}`, 'restore'); project.updatedAt = this.clock(); await this.save(); return this.summary(project);
  }

  async startPreview(id) {
    const project = this.get(id); if (!project.lastValidatedRevision) throw new Error('A validated build is required before previewing.');
    if (!this.previewStarter) return { state: 'not_started', target: null };
    const preview = await this.previewStarter({ project, workspace: this.workspace(project.id), command: spawnProcess }); project.preview = { ...preview, updatedAt: this.clock() }; await this.save(); return project.preview;
  }
}
